#!/usr/bin/env node
/**
 * Generates src/config/colors-oklch.js from Tailwind v4's theme.css so the
 * opt-in oklch palette (theme.palette: 'oklch') matches Tailwind v4 exactly.
 *   node scripts/generate-oklch-palette.js
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const themeCss = readFileSync(join(dirname(require.resolve('tailwindcss/package.json')), 'theme.css'), 'utf8');
const version = require('tailwindcss/package.json').version;
const out = {};
for (const m of themeCss.matchAll(/--color-([a-z]+-(?:50|[1-9]00|950)):\s*(oklch\([^)]*\));/g)) out[m[1]] = m[2];
if (Object.keys(out).length < 200) throw new Error('unexpected theme.css shape');
const body = Object.entries(out).map(([k, v]) => `  '${k}': '${v}'`).join(',\n');
const file = `/**
 * Tailwind v${version} oklch palette (generated by scripts/generate-oklch-palette.js — do not edit).
 * Enabled with \`theme: { palette: 'oklch' }\`; the default palette stays the hex (v3) one.
 */
export const OKLCH_PALETTE = {
${body}
};

export default OKLCH_PALETTE;
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'config', 'colors-oklch.js'), file);
console.log(`✓ src/config/colors-oklch.js (${Object.keys(out).length} colours from tailwindcss ${version})`);
